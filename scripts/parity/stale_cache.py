"""The stale-`WMIYearValidChars` divergence class, enumerated from the dump.

`vpic.spvindecode_errorcode` does not compute the per-position valid characters
that drive its suggested-VIN / error-byte / unused-position logic: it reads them
out of the `vpic.wmiyearvalidchars` cache and recomputes only when a
`(wmi, year)` cell has no rows at all. ultravin always recomputes. Every cell
where the cache disagrees with the recompute is therefore a *known, machine-
provable* ultravin-vs-oracle divergence surface — argued in full at
docs/KNOWN_DEVIATIONS.md#stale-wmiyearvalidchars-cache.

`vpic-import --stale-cache-report` diffs every cell of a dump's cache against the
recompute from that same dump's own pattern rows (`ultravin::recompute_valid_chars`,
the decoder's code path). `scripts/stale_cache_cells.json` is the `(wmi, year)`
list distilled from that scan, regenerated by every monthly refresh. This module
turns that list into a verdict on one observed divergence.

**What keeps a decoder bug out of here.** Not the list's independence: it is
derived by running the decoder's own charset code over the dump, so a bug in
`recompute_valid_chars` would move both the list and the decode together. What
bounds the excuse is (a) `answerkey verify`, which re-checks every frozen VIN's
*whole* decode on every PR and is not consulted here at all, (b) the frozen unit
tests in `crates/ultravin/src/errors.rs`, which pin the charset rendering, and
(c) the refresh's jump gate, which fails a month whose newly-stale cell count
leaps — the shape a charset regression takes. On top of those, what a listed
cell buys is narrow by construction: the divergence must touch only the
error/correction elements the cache feeds, must land on the very cell that VIN's
decode reads (`fVinWMI` + the model year the decode chose), and must point at a
VIN position the cache and the recompute actually disagree at. Anything wider —
a different vehicle, a different model year, a different position — stays a bug,
or stays registered per VIN in `scripts/known_problems.json`.

**Why the printed positions are not the whole class.** The cache feeds
`spvindecode_errorcode`, and that proc does more with the charsets than print
them: it counts how many positions failed, and the count picks which branch
renders the result (one error prints a resolved character, several print `!`
with the full charsets) and which model year the surrounding `spvindecode`
settles on. A single stale position can therefore re-render positions that are
not stale and years that are not wrong, and no containment test over the
*printed* positions can ever recognise that — the evidence has been laundered by
the time it reaches the diff.

`counterfactual_rows` settles those the only way that is sound: by running the
experiment. Freshen the oracle's cache — the proc's own
`fExtractValidCharsPerWmiYear`, the function the cache is a stale materialisation
of — re-decode, and excuse the VIN only if the freshened oracle now reproduces
ultravin byte for byte. No modelling of the branch logic, no position arithmetic,
and fail-closed by construction: anything the freshened oracle still disagrees
about is, by definition, not explained by the cache.
"""

