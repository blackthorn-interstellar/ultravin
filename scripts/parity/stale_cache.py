def expected_in_sweep(report: dict[str, Any]) -> list[str]:
    """The diverging sweep VINs whose divergence is this class."""
    return sorted({e["vin"] for e in report.get("examples", []) if is_expected_divergence(e["vin"], e)})


def expected_in_corpus(corpus: dict[str, Any]) -> list[str]:
    """The diverging frozen-corpus VINs whose frozen difference is this class."""
    return sorted({e["vin"] for e in corpus.get("entries", []) if is_expected_divergence(e["vin"], e["expected_diff"])})


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("cells", help="regenerate the cell list from a --stale-cache-report scan")
    c.add_argument("--report", required=True, help="the scan's JSON report")
    c.add_argument("--out", default=str(CELLS), help="cell list to write")
    e = sub.add_parser("expected", help="VINs whose divergence is the known stale-cache class")
    e.add_argument("--sweep", default="", help="a scripts.parity.sweep report")
    e.add_argument("--corpus", default="", help="tests/parity_corpus.json")
    e.add_argument("--out", default="-", help="JSON output (default stdout)")
    args = ap.parse_args(argv)

    if args.cmd == "cells":
        doc = write_cells(json.loads(Path(args.report).read_text()), Path(args.out))
        problems = consistency_errors(doc)
        print(f"{len(doc['cells'])} stale cells ({doc['dump']}) -> {args.out}", file=sys.stderr)
        for problem in problems:
            print(f"INCONSISTENT: {problem}", file=sys.stderr)
        return 1 if problems else 0

    payload = {
        "sweep": expected_in_sweep(json.loads(Path(args.sweep).read_text())) if args.sweep else [],
        "corpus": expected_in_corpus(json.loads(Path(args.corpus).read_text())) if args.corpus else [],
    }
    text = json.dumps(payload, indent=2) + "\n"
    if args.out == "-":
        print(text, end="")
    else:
        Path(args.out).write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
